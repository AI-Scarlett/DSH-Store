  echo "[+] 从本地代码仓库复制后端服务代码..."
  cp "$REPO_ROOT/package.json" "$SERVICE_DIR/"
  cp "$REPO_ROOT/src/ai-model-settings.mjs" "$SERVICE_DIR/src/"
  cp "$REPO_ROOT/src/ai-recommend.mjs" "$SERVICE_DIR/src/"
