echo "  DSH Store 大模型后台配置与推荐服务一键部署程序  "
echo "=================================================="

if [ "$(id -u)" -ne 0 ]; then
  echo "[!] 错误：请以 root 权限运行此脚本：sudo bash $0" >&2
  exit 1
fi

node_bin="$(command -v node || true)"
if [ -z "$node_bin" ]; then
  for candidate in /usr/bin/node /usr/local/bin/node /snap/bin/node; do
    if [ -x "$candidate" ]; then
      node_bin="$candidate"
      break
    fi
  done
fi

if [ -z "$node_bin" ]; then
  echo "[*] 未检测到 Node.js，正在尝试安装..."
