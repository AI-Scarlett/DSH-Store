import sys
path = sys.argv[1]
with open(path, "r", encoding="utf-8") as f:
    c = f.read()
idx = c.rfind("}")
if idx != -1:
    new_c = c[:idx] + "
    # DSH Store AI API Include
    include /etc/nginx/snippets/dsh-model-api.conf;
" + c[idx:]
    with open(path, "w", encoding="utf-8") as f:
        f.write(new_c)
    print("    -> 规则注入成功")
PY
