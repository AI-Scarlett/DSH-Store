  echo "[+] 从本地代码仓库复制后端服务代码..."
  cp "$REPO_ROOT/package.json" "$SERVICE_DIR/"
  cp "$REPO_ROOT/src/ai-model-settings.mjs" "$SERVICE_DIR/src/"
  cp "$REPO_ROOT/src/ai-recommend.mjs" "$SERVICE_DIR/src/"
  cp "$REPO_ROOT/src/author-exclusions.mjs" "$REPO_ROOT/src/catalog.mjs" "$REPO_ROOT/src/bundle-patch-contract.mjs" "$SERVICE_DIR/src/"
  cp "$REPO_ROOT/marketplace/rankings/model.js" "$SERVICE_DIR/marketplace/rankings/"
  cp "$REPO_ROOT/marketplace/lib/community-recommendations.js" "$SERVICE_DIR/marketplace/lib/"
  cp "$REPO_ROOT/scripts/serve-marketplace.mjs" "$SERVICE_DIR/scripts/"
